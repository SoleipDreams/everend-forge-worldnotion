export function timelineText(locale: "en" | "es") {
  return (value: string): string => {
    if (locale !== "es") return value;
    if (SPANISH[value]) return SPANISH[value];
    const integer = /^(.*) must be an integer between (.*) and (.*)$/.exec(value);
    if (integer)
      return `${SPANISH[integer[1]] ?? integer[1]} debe ser un entero entre ${integer[2]} y ${integer[3]}`;
    return value;
  };
}
